def build_tasks():
    tasks = []
    for name, front, side, back, parts in PIECES:
        d = ROOT / name
        d.mkdir(parents=True, exist_ok=True)
        (d / "部件清单.txt").write_text(f"{name}\n\n部件清单：\n{parts}\n", encoding="utf-8")
        tasks.append({"id": f"{name}-正面", "dir": name, "stem": "正面",
                      "desc": front, "ratio": "2:3", "res": "1K", "ref": None})
        tasks.append({"id": f"{name}-侧面", "dir": name, "stem": "侧面",
                      "desc": f"将图中主体旋转至正侧面90°视角，其余全部不变。{SIDE_EXTRA}侧面需完整可见：{side}。",
                      "ratio": "2:3", "res": "1K", "ref": f"{name}-正面"})
        tasks.append({"id": f"{name}-背面", "dir": name, "stem": "背面",
                      "desc": f"将图中主体旋转至正后方180°视角，其余全部不变。{BACK_EXTRA}背面需完整可见：{back}。",
                      "ratio": "2:3", "res": "1K", "ref": f"{name}-正面"})
    bd = ROOT / "棋盘"; bd.mkdir(exist_ok=True)
    for nm, ratio, res, desc in BOARD:
        tasks.append({"id": nm, "dir": "棋盘", "stem": nm, "desc": desc, "ratio": ratio, "res": res, "ref": None})
    ed = ROOT / "环境"; ed.mkdir(exist_ok=True)
    for nm, ratio, res, desc in ENV:
        tasks.append({"id": nm, "dir": "环境", "stem": nm, "desc": desc, "ratio": ratio, "res": res, "ref": None})
    return tasks

def load_state():
    if STATE.exists():
        return json.loads(STATE.read_text(encoding="utf-8"))
    return {}

def save_state(st):
    STATE.write_text(json.dumps(st, ensure_ascii=False, indent=1), encoding="utf-8")

def run_tool(args):
    r = subprocess.run([sys.executable, str(TOOL)] + args, cwd=str(PLUGIN),
                       capture_output=True, text=True, encoding="utf-8", errors="replace", timeout=280)
    return (r.stdout or "") + (r.stderr or "")

def find_output(dirpath, stem):
    for ext in (".png", ".jpg", ".jpeg"):
        p = dirpath / (stem + ext)
        if p.exists() and p.stat().st_size > 10000:
            return str(p)
    return None

def main():
    batch = int(sys.argv[1]) if len(sys.argv) > 1 else 3
    tasks = build_tasks()
    state = load_state()
    done_count = 0
    for t in tasks:
        if done_count >= batch:
            break
        if t["id"] in state:
            continue
        dirpath = ROOT / t["dir"]
        existing = find_output(dirpath, t["stem"])
        if existing:
            state[t["id"]] = existing
            save_state(state)
            continue
        out = dirpath / (t["stem"] + ".png")
        args = ["generate", "--description", t["desc"], "--ratio", t["ratio"],
                "--resolution", t["res"], "--background", "opaque", "--output", str(out)]
        if t["ref"]:
            ref_path = state.get(t["ref"]) or find_output(dirpath, "正面")
            if not ref_path:
                print(f"[SKIP] {t['id']}: 参考图 {t['ref']} 尚未生成", flush=True)
                continue
            print(f"[UPLOAD] {t['ref']} -> url ...", flush=True)
            up = run_tool(["image-to-url", "--image-path", ref_path])
            m = re.search(r"https?://\S+", up)
            if not m:
                print(f"[FAIL-UPLOAD] {t['id']}: {up[-500:]}", flush=True)
                continue
            args += ["--reference-image", m.group(0)]
        print(f"[GEN] {t['id']} ...", flush=True)
        try:
            log = run_tool(args)
        except subprocess.TimeoutExpired:
            print(f"[TIMEOUT] {t['id']}", flush=True)
            continue
        saved = find_output(dirpath, t["stem"])
        if saved:
            state[t["id"]] = saved
            save_state(state)
            done_count += 1
            print(f"[OK] {t['id']} -> {saved}", flush=True)
        else:
            print(f"[FAIL] {t['id']}: {log[-800:]}", flush=True)
    remaining = [t["id"] for t in tasks if t["id"] not in load_state()]
    print(f"=== done_this_run={done_count}, remaining={len(remaining)} ===", flush=True)
    for r in remaining:
        print("  - " + r, flush=True)

if __name__ == "__main__":
    main()
